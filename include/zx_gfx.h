/**
 * @file zx_gfx.h
 * @brief Библиотека графических функций для ZX Spectrum (компилятор SDCC)
 *
 * Данная библиотека предоставляет базовые функции для работы с графикой ZX Spectrum
 *
 * Все функции используют прямую запись в фреймбуффер для ускорения работы
 *
 * Автор: Dmitry Panin UA3REO
 * Компилятор: SDCC
 * Целевая платформа: ZX Spectrum
 */

#ifndef ZXCLIB_GFX
#define ZXCLIB_GFX

#include "zx_48k.h"
#include <string.h> // memset

extern uint16_t ZX_GFX_VIDEO_PTR;
extern uint16_t ZX_GFX_VIDEO_ATTR_PTR;

/**
 * @brief Очистка пикселя напрямую в фреймбуффере
 * @param x Координата X (0-255)
 * @param y Координата Y (0-191)
 *
 * Сбрасывает указанный пиксель в видеопамяти.
 * Работает напрямую с фреймбуффером для максимальной скорости.
 */
void ZX_GFX_clear_pixel(uint8_t x, uint8_t y);

/**
 * @brief Очистка всего экрана (удаление всех пикселей)
 *
 * Очищает все пиксели в видеопамяти, устанавливая все биты в 0.
 * Атрибуты экрана остаются без изменений.
 */
void ZX_GFX_clear_screen(void);

/**
 * @brief Отрисовка круга (алгоритм Брезенхэма)
 * @param cx Центральная координата X
 * @param cy Центральная координата Y
 * @param radius Радиус круга
 *
 * Рисует круг используя алгоритм Брезенхэма для максимальной точности.
 */
void ZX_GFX_draw_circle(uint8_t cx, uint8_t cy, uint8_t radius);

/**
 * @brief Отрисовка эллипса
 * @param cx Центральная координата X
 * @param cy Центральная координата Y
 * @param rx Радиус по оси X
 * @param ry Радиус по оси Y
 *
 * Рисует эллипс используя модифицированный алгоритм Брезенхэма.
 */
void ZX_GFX_draw_ellipse(uint8_t cx, uint8_t cy, uint8_t rx, uint8_t ry);

/**
 * @brief Отрисовка глифа 8x8 пикселей
 * @param x Начальная координата X
 * @param y Начальная координата Y
 * @param buffer Указатель на буфер с пикселями
 *
 * Копирует битмап из буфера в видеопамять.
 */
void ZX_GFX_draw_gliph(uint8_t x, uint8_t y, const uint8_t *buffer);

/**
 * @brief Быстрая отрисовка горизонтальной линии
 * @param x1 Начальная координата X (0-255)
 * @param x2 Конечная координата X (0-255)
 * @param y Координата Y (0-191)
 *
 * Оптимизированная функция для рисования строго горизонтальных линий.
 * Использует побайтные операции для рисования 8 пикселей одновременно.
 */
void ZX_GFX_draw_horizontal_line(uint8_t x1, uint8_t x2, uint8_t y);

/**
 * @brief Отрисовка линии (алгоритм Брезенхэма)
 * @param x1 Начальная координата X
 * @param y1 Начальная координата Y
 * @param x2 Конечная координата X
 * @param y2 Конечная координата Y
 *
 * Рисует линию между двумя точками используя алгоритм Брезенхэма.
 * Работает с линиями под любым углом.
 */
void ZX_GFX_draw_line(uint8_t x1, uint8_t y1, uint8_t x2, uint8_t y2);

/**
 * @brief Отрисовка пикселя напрямую в фреймбуффер
 * @param x Координата X (0-255)
 * @param y Координата Y (0-191)
 *
 * Устанавливает указанный пиксель в видеопамяти.
 * Работает напрямую с фреймбуффером для максимальной скорости.
 */
void ZX_GFX_draw_pixel(uint8_t x, uint8_t y);

/**
 * @brief Отрисовка прямоугольника
 * @param x1 Левая верхняя координата X
 * @param y1 Левая верхняя координата Y
 * @param x2 Правая нижняя координата X
 * @param y2 Правая нижняя координата Y
 *
 * Рисует прямоугольник с заданными координатами.
 * Использует оптимизированные функции для горизонтальных и вертикальных линий.
 */
void ZX_GFX_draw_rectangle(uint8_t x1, uint8_t y1, uint8_t x2, uint8_t y2);

/**
 * @brief Отрисовка прямоугольника с закругленными углами
 * @param x1 Левая верхняя координата X
 * @param y1 Левая верхняя координата Y
 * @param x2 Правая нижняя координата X
 * @param y2 Правая нижняя координата Y
 * @param radius Радиус закругления углов
 *
 * Рисует прямоугольник с закругленными углами.
 */
void ZX_GFX_draw_rounded_rectangle(uint8_t x1, uint8_t y1, uint8_t x2, uint8_t y2, uint8_t radius);

/**
 * @brief Отрисовка треугольника по трем точкам
 * @param x1 Первая вершина X
 * @param y1 Первая вершина Y
 * @param x2 Вторая вершина X
 * @param y2 Вторая вершина Y
 * @param x3 Третья вершина X
 * @param y3 Третья вершина Y
 *
 * Рисует треугольник соединяя три линии между вершинами.
 */
void ZX_GFX_draw_triangle(uint8_t x1, uint8_t y1, uint8_t x2, uint8_t y2, uint8_t x3, uint8_t y3);

/**
 * @brief Быстрая отрисовка вертикальной линии
 * @param x Координата X (0-255)
 * @param y1 Начальная координата Y (0-191)
 * @param y2 Конечная координата Y (0-191)
 *
 * Оптимизированная функция для рисования строго вертикальных линий.
 * Использует прямой доступ к памяти и предвычисленные маски.
 */
void ZX_GFX_draw_vertical_line(uint8_t x, uint8_t y1, uint8_t y2);

/**
 * @brief Отрисовка заполненного круга
 * @param cx Центральная координата X
 * @param cy Центральная координата Y
 * @param radius Радиус круга
 *
 * Рисует заполненный круг используя горизонтальные линии.
 */
void ZX_GFX_fill_circle(uint8_t cx, uint8_t cy, uint8_t radius);

/**
 * @brief Отрисовка заполненного прямоугольника
 * @param x1 Левая верхняя координата X
 * @param y1 Левая верхняя координата Y
 * @param x2 Правая нижняя координата X
 * @param y2 Правая нижняя координата Y
 *
 * Рисует заполненный прямоугольник с заданными координатами.
 */
void ZX_GFX_fill_rectangle(uint8_t x1, uint8_t y1, uint8_t x2, uint8_t y2);

/**
 * @brief Отрисовка заполненного прямоугольника с закругленными углами
 * @param x1 Левая верхняя координата X
 * @param y1 Левая верхняя координата Y
 * @param x2 Правая нижняя координата X
 * @param y2 Правая нижняя координата Y
 * @param radius Радиус закругления углов
 *
 * Рисует заполненный прямоугольник с закругленными углами.
 */
void ZX_GFX_fill_rounded_rectangle(uint8_t x1, uint8_t y1, uint8_t x2, uint8_t y2, uint8_t radius);

/**
 * @brief Заливка всего экрана указанными атрибутами
 * @param ink Цвет чернил (переднего плана)
 * @param paper Цвет фона
 * @param bright Яркость
 * @param flash Мигание
 *
 * Заполняет весь экран указанными атрибутами. Мигание всегда выключено.
 */
void ZX_GFX_fill_screen(zx_color_t ink, zx_color_t paper, zx_bright_t bright, zx_flash_t flash);

/**
 * @brief Отрисовка заполненного треугольника
 * @param x1 Первая вершина X
 * @param y1 Первая вершина Y
 * @param x2 Вторая вершина X
 * @param y2 Вторая вершина Y
 * @param x3 Третья вершина X
 * @param y3 Третья вершина Y
 *
 * Рисует заполненный треугольник используя алгоритм заполнения по строкам.
 */
void ZX_GFX_fill_triangle(uint8_t x1, uint8_t y1, uint8_t x2, uint8_t y2, uint8_t x3, uint8_t y3);

/**
 * @brief Получение атрибутов по координатам
 * @param x Координата X (0-255)
 * @param y Координата Y (0-191)
 * @return Байт атрибутов для указанной позиции
 *
 * Возвращает байт атрибутов (цвет, яркость, мигание) для символьной ячейки,
 * в которой находится указанный пиксель.
 */
uint8_t ZX_GFX_get_attributes(uint8_t x, uint8_t y);

/**
 * @brief Получение адреса пикселя в видеопамяти по координатам
 * @param x Координата X (0-255)
 * @param y Координата Y (0-191)
 * @return Указатель на байт видеопамяти, содержащий пиксель
 *
 * Вычисляет адрес байта видеопамяти, в котором находится указанный пиксель.
 * Используется для быстрой работы с пикселями напрямую.
 */
inline uint8_t *ZX_GFX_get_pixel_address(uint8_t x, uint8_t y);

/**
 * @brief Получение маски бита для пикселя в байте
 * @param x Координата X (0-255)
 * @return Маска бита (0x80, 0x40, 0x20, 0x10, 0x08, 0x04, 0x02, 0x01)
 *
 * Возвращает маску для установки/сброса конкретного бита в байте видеопамяти.
 */
inline uint8_t ZX_GFX_get_pixel_mask(uint8_t x);

/**
 * @brief Получение состояния пикселя по координатам
 * @param x Координата X (0-255)
 * @param y Координата Y (0-191)
 * @return 1 если пиксель включен, 0 если выключен
 *
 * Читает состояние пикселя из видеопамяти.
 */
bool ZX_GFX_get_pixel(uint8_t x, uint8_t y);

/**
 * @brief Установка атрибутов для блока пикселей
 * @param x1 Начальная координата X (0-255)
 * @param y1 Начальная координата Y (0-191)
 * @param x2 Конечная координата X (0-255)
 * @param y2 Конечная координата Y (0-191)
 * @param ink Цвет чернил (переднего плана)
 * @param paper Цвет фона
 * @param bright Яркость
 * @param flash Мигание
 *
 * Устанавливает атрибуты для всех символьных ячеек в указанном прямоугольнике.
 */
void ZX_GFX_set_block_attributes(uint8_t x1, uint8_t y1, uint8_t x2, uint8_t y2, zx_color_t ink, zx_color_t paper, zx_bright_t bright, zx_flash_t flash);

/**
 * @brief Установка атрибутов для пикселя
 * @param x Координата X (0-255)
 * @param y Координата Y (0-191)
 * @param ink Цвет чернил (переднего плана)
 * @param paper Цвет фона
 * @param bright Яркость
 * @param flash Мигание
 *
 * Устанавливает атрибуты для символьной ячейки, в которой находится указанный пиксель.
 */
void ZX_GFX_set_pixel_attributes(uint8_t x, uint8_t y, zx_color_t ink, zx_color_t paper, zx_bright_t bright, zx_flash_t flash);

/**
 * @brief Установка яркости для пикселя
 * @param x Координата X (0-255)
 * @param y Координата Y (0-191)
 * @param bright Яркость ZX_BRIGHT_NORMAL / ZX_BRIGHT_HIGH
 *
 * Устанавливает только режим яркости, сохраняя остальные атрибуты.
 */
void ZX_GFX_set_pixel_bright(uint8_t x, uint8_t y, zx_bright_t bright);

/**
 * @brief Установка мигания для пикселя
 * @param x Координата X (0-255)
 * @param y Координата Y (0-191)
 * @param flash Мигание ZX_FLASH_OFF / ZX_FLASH_ON
 *
 * Устанавливает только режим мигания, сохраняя остальные атрибуты.
 */
void ZX_GFX_set_pixel_flash(uint8_t x, uint8_t y, zx_flash_t flash);

/**
 * @brief Установка цвета чернил (переднего плана) для пикселя
 * @param x Координата X (0-255)
 * @param y Координата Y (0-191)
 * @param ink Цвет чернил
 *
 * Устанавливает только цвет переднего плана, сохраняя остальные атрибуты.
 */
void ZX_GFX_set_pixel_ink(uint8_t x, uint8_t y, zx_color_t ink);

/**
 * @brief Установка цвета фона для пикселя
 * @param x Координата X (0-255)
 * @param y Координата Y (0-191)
 * @param paper Цвет фона
 *
 * Устанавливает только цвет фона, сохраняя остальные атрибуты.
 */
void ZX_GFX_set_pixel_paper(uint8_t x, uint8_t y, zx_color_t paper);

/**
 * @brief Устанавливает адрес видео-буфера, куда GFX будет выводить изображение (например в обычный или SHADOW банк)
 * @param addr Адрес начала видео памяти 0x0000 - 0xC0000
 *
 * Вычисляет адрес аттрибутов автоматически, по смещению
 */
void ZX_GFX_set_video_addr(uint16_t addr);

#endif
